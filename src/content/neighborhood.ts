import { hotel } from "@/content/site";

/**
 * Ориентиры рядом с отелем для радиальной схемы на главной («Об отеле»).
 *
 * Время и азимут — реальные, проверены по пешим маршрутам Яндекс Карт от
 * ул. Марата, 30 (проверено 2026-09-27). Азимут — направление по компасу от
 * отеля (0° = север, по часовой стрелке), округлён; для Думской и
 * Казанского собора (почти совпадающие реальные направления, ~300–301°)
 * взято характерное направление «вдоль Невского на запад» — расхождение в
 * пределах пары градусов не искажает картину, это стилизованная схема, а
 * не точная карта улиц.
 *
 * Не добавлять сюда ориентиры без проверки реального маршрута — схема
 * заявляет честные расстояния, это её единственная ценность.
 */
export interface Landmark {
  name: string;
  minutes: number;
  /** Азимут от отеля, градусы по часовой от севера */
  bearingDeg: number;
}

const OTHER_LANDMARKS: Landmark[] = [
  { name: "Невский проспект", minutes: 12, bearingDeg: 344 },
  { name: "Думская улица", minutes: 26, bearingDeg: 300 },
  { name: "Казанский собор", minutes: 30, bearingDeg: 301 },
];

export const landmarks: Landmark[] =
  hotel.metroStation && hotel.metroMinutes != null
    ? [
        { name: `Метро «${hotel.metroStation}»`, minutes: hotel.metroMinutes, bearingDeg: 295 },
        ...OTHER_LANDMARKS,
      ]
    : OTHER_LANDMARKS;
