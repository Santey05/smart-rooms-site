export interface HotelInfo {
  name: string;
  /** Полный почтовый адрес */
  address: string | null;
  /** Координаты для карты (источник — Яндекс Карты, геокодирование адреса) */
  coords: { lat: number; lon: number } | null;
  /** Год постройки дома, если известен (источник — 2ГИС) */
  builtYear: number | null;
  /** Ближайшая станция метро */
  metroStation: string | null;
  /** Время пешком до метро в минутах (маршрут на карте, подтверждён владельцем) */
  metroMinutes: number | null;
  /** Телефон в международном формате, например "+7 900 000-00-00" */
  phone: string | null;
  /** Ссылка на WhatsApp/Telegram, например "https://wa.me/79000000000" */
  messengerHref: string | null;
  email: string | null;
  /** Форматы заселения, подтверждённые владельцем отеля. */
  checkInMethod: string | null;
  /** Время или условия заезда, утверждённые отелем. */
  checkInTime: string | null;
  /** Время выезда, например "12:00" */
  checkOutTime: string | null;
}

